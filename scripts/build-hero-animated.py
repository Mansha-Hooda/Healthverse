def build_sprites():
    sizes = L.icon_render_size()
    rows, total = [], 0
    os.makedirs(WEBP_OUT, exist_ok=True)
    for icon in sorted(L.SPRITES):
        sheet_name = L.SPRITES[icon][0]
        sheet = Image.open(os.path.join(SHEETS, sheet_name)).convert("RGBA")
        x, y, w, h = L.sprite_crop(icon, sheet.width, sheet.height)
        box = (max(0, round(x)), max(0, round(y)),
               min(sheet.width, round(x + w)), min(sheet.height, round(y + h)))
        draw_w, draw_h = sizes[icon]
        target = (round(draw_w * SCALE), round(draw_h * SCALE))
        out = sheet.crop(box).resize(target, Image.LANCZOS)
        path = os.path.join(WEBP_OUT, f"object-{icon}.webp")
        out.save(path, "WEBP", quality=90, method=6)
        kb = os.path.getsize(path) / 1024
        total += kb
        rows.append(f"  object-{icon + '.webp':<18} {target[0]:>3}x{target[1]:<4} "
                    f"{kb:5.1f} KB  from {sheet_name} {box}")
    return rows, total


def build_spec():
    def entry(**kw):
        """Values arrive already in TS form — strings pre-quoted, numbers raw."""
        return "  { " + ", ".join(f"{k}: {v}" for k, v in kw.items()) + " },"

    def n(value):
        """3dp is well below a device pixel; drop a trailing `.0` while there."""
        return f"{round(value, 3):g}"

    def quoted(value):
        return '"' + value.replace('"', '\\"') + '"'

    lines = [
        "// AUTO-GENERATED by scripts/build-hero-animated.py — "
        "do not edit by hand.",
        '// Source: Figma "Health Verse Revamp_Jan25", node 1208:3049 '
        '"Header/ Animated".',
        "//",
        "// Every number is in CSS pixels within the 360x367 frame. Figma's "
        "frame is",
        "// 360x395; the top 28px is a device status bar, which is not "
        "rendered for",
        "// the same reason Header.tsx omits it.",
        "",
        f"export const FRAME_WIDTH = {L.FRAME_WIDTH};",
        f"export const FRAME_HEIGHT = {L.FRAME_HEIGHT};",
        f"export const LOOP_SECONDS = {M.LOOP_SECONDS};",
        "",
        "/** Figma: brand-blue/Gradients - Brand/Dark/900 -> 700 (45deg). */",
        "export const BACKGROUND =",
        f'  "linear-gradient({L.BACKGROUND["angle"]}deg in srgb, '
        f'{L.BACKGROUND["from"][1]} 0%, {L.BACKGROUND["to"][1]} 100%)";',
        "",
    ]

    rx, ry, rw, rh = L.place(L.RING["box"])
    lines += [
        "export const RING = {",
        f"  left: {n(rx)}, top: {n(ry)}, size: {n(rw)},",
        f"  outer: {{ r: {L.RING['outer']['r']}, "
        f"width: {L.RING['outer']['stroke_width']}, "
        f"opacity: {L.RING['outer']['opacity']} }},",
        f"  inner: {{ r: {L.RING['inner']['r']}, "
        f"width: {L.RING['inner']['stroke_width']}, "
        f"opacity: {L.RING['inner']['opacity']} }},",
        f"  dot: {{ cx: {L.RING['dot']['cx']}, cy: {L.RING['dot']['cy']}, "
        f"r: {L.RING['dot']['r']}, opacity: {L.RING['dot']['opacity']} }},",
        "} as const;",
        "",
    ]
    assert abs(rw - rh) < 1e-6, "ring must be square"

    bx, by, bw, _bh = L.place(L.BADGE["box"])
    lines += [
        "export const BADGE = {",
        f"  left: {n(bx)}, top: {n(by)}, width: {n(bw)},",
        f"  iconSize: {L.BADGE['icon_size']}, gap: {L.BADGE['gap']},",
        f"  text: {quoted(L.BADGE['text'])},",
        "} as const;",
        "",
    ]

    hx, hy, hw, _hh = L.place(L.HERO_WORD["box"])
    lines += [
        "export const HERO_WORD = {",
        f"  left: {n(hx)}, top: {n(hy)}, width: {n(hw)},",
        f"  text: {quoted(L.HERO_WORD['text'])},",
        f"  shadow: {quoted(L.HERO_WORD['shadow'])},",
        "} as const;",
        "",
        "export type HeroTag = {",
        "  id: string; text: string; token: string;",
        "  left: number; top: number; width: number; height: number;",
        "};",
        "",
        f"/** All four are rotated {L.TAG_ROTATION} degrees in Figma. */",
        f"export const TAG_ROTATION = {L.TAG_ROTATION};",
        "",
        "export const TAGS: HeroTag[] = [",
    ]
    for tag in L.TAGS:
        x, y, w, h = L.place(tag["box"], L.TAG_ROTATION)
        lines.append(entry(id=quoted(tag["id"]), text=quoted(tag["text"]),
                           token=quoted(tag["token"]),
                           left=n(x), top=n(y), width=n(w), height=n(h)))
    lines += [
        "];",
        "",
        "export type HeroProof = {",
        "  id: string; text: string;",
        "  left: number; top: number; width: number;",
        "};",
        "",
        "export const PROOFS: HeroProof[] = [",
    ]
    for proof in L.PROOFS:
        x, y, w, _h = L.place(proof["box"])
        lines.append(entry(id=quoted(proof["id"]), text=quoted(proof["text"]),
                           left=n(x), top=n(y), width=n(w)))
    lines += [
        "];",
        "",
        "export type HeroObject = {",
        "  id: string; icon: string;",
        "  left: number; top: number; width: number; height: number;",
        "};",
        "",
        "/** Listed back-to-front, which is also the order they render in. */",
        "export const OBJECTS: HeroObject[] = [",
    ]
    for obj in L.OBJECTS:
        x, y, w, h = L.place(obj["box"], obj["rest_rotation"])
        lines.append(entry(id=quoted(obj["id"]), icon=quoted(obj["icon"]),
                           left=n(x), top=n(y), width=n(w), height=n(h)))
    lines.append("];")
    return "\n".join(lines) + "\n"


REST_ROTATION = {obj["node"]: obj["rest_rotation"] for obj in L.OBJECTS}


def phase_of(name):
    """Which quarter of the loop a node belongs to, or None for the ring."""
    if name.startswith("object"):
        return int(name[len("object")])
    if name.startswith(("tag ", "proof ")):
        return int(name.split()[1])
    return None


def still_declarations(node_id, name, role, props):
    """The node's appearance in Figma's own static render of the frame.

    That render shows phase 1 only, with every node at its canvas position
    and rest rotation, so the values come from the layout spec rather than
    from the timeline. Freezing the timeline instead would catch the objects
    mid-bob — they never fully stop — and would leak object3.1, whose
    opacity track dips across the whole first half of the loop.
    """
    if role == "ring":
        return ["rotate: 0deg;"]
    if phase_of(name) != 1:
        return ["opacity: 0;"]

    out = ["opacity: 1;"]
    if "rotate" in props:
        out.append(f"rotate: {num(REST_ROTATION[node_id])}deg;")
    if "scale" in props:
        out.append("scale: 1;")
    if "scaleY" in props:
        out.append("scale: 1 1;")
    if "x" in props or "y" in props:
        out.append("translate: 0px 0px;")
    return out


def build_css():
    parts = [BANNER]
    rules, stills = [], []
    for node_id, (name, role, props) in M.TRACKS.items():
        block, slug, animations = node_rules(node_id, name, role, props)
        parts.append(block)
        shorthand = ",\n    ".join(
            f"{kf} {M.LOOP_SECONDS}s linear infinite" for kf in animations)
        # Everything but the ring starts invisible, so no object flashes in
        # the frame between first paint and the animation's first tick.
        hidden = "" if role == "ring" else "\n  opacity: 0;"
        rules.append(
            f".{PREFIX}-{slug} {{\n  animation:\n    {shorthand};{hidden}\n}}")
        decls = " ".join(still_declarations(node_id, name, role, props))
        stills.append(f"  .{PREFIX}-{slug} {{ animation-name: none; {decls} }}")

    parts.append("/* Element hooks. Each node drives one CSS property per\n"
                 "   track, so the tracks never fight over `transform`. */")
    parts.extend(rules)

    parts.append(
        "/* The global reduced-motion rule in globals.css collapses every\n"
        "   animation onto its 100% frame, which here is the moment after\n"
        "   the fourth phase has left — an empty header. Drop the animations\n"
        "   outright instead and hold the frame Figma itself renders. */\n"
        "@media (prefers-reduced-motion: reduce) {\n"
        + "\n".join(stills) + "\n}")
    return "\n\n".join(parts) + "\n"


def main():
    if not os.path.isdir(SHEETS):
        sys.exit(f"missing {SHEETS} — re-download the Figma sprite sheets first")

    problems = M.validate()
    if problems:
        for line in problems:
            print("FAIL", line)
        sys.exit("motion spec is malformed")

    rows, total = build_sprites()
    print("sprites")
    print("\n".join(rows))
    print(f"  {'total':<18} {total:.0f} KB (sheets were ~2.5 MB)\n")

    os.makedirs(os.path.dirname(SPEC_OUT), exist_ok=True)
    spec = build_spec()
    with open(SPEC_OUT, "w", encoding="utf-8") as fh:
        fh.write(spec)
    print(f"wrote {os.path.relpath(SPEC_OUT, ROOT)} ({len(spec):,} chars)")

    css = build_css()
    with open(CSS_OUT, "w", encoding="utf-8") as fh:
        fh.write(css)
    print(f"wrote {os.path.relpath(CSS_OUT, ROOT)} ({len(css):,} chars, "
          f"{css.count('@keyframes')} keyframe rules)")


main()
